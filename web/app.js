/* app.js: shared state + screen router (Danielle)
 *
 * Contract for views (Som's modules follow the same one):
 *   window.Views.<mode> = { mount(el, data), update(state, patch), unmount() }
 *   - mount():  build the screen inside el
 *   - update(): called on every setState while this view is active
 *   - unmount(): optional cleanup
 *
 * Extra hooks:
 *   window.Views.card = { open(studentId) }   -> Som's interrogation card
 *   App.selectStudent(id) sets state and calls Views.card.open if present.
 */
(function () {
  const state = {
    currentTime: null,      // minutes after midnight: drives clock + map
    selectedStudent: null,  // student ID: drives card + highlights
    mode: 'summary',        // 'summary' | 'timeline' | 'network' | 'map' | 'story' | 'evidence'
    storyStep: 0,           // index into findings[]
    revealMode: false       // true = show kingpin links + fade clean students
  };

  const listeners = [];
  window.Views = window.Views || {};

  const TABS = [
    { mode: 'summary',  label: 'Case' },
    { mode: 'story',    label: 'Story' },
    { mode: 'map',      label: 'Map' },
    { mode: 'timeline', label: 'Timeline' },
    { mode: 'network',  label: 'Network' }
  ];

  const App = {
    state,
    data: null,
    byId: {},
    placeById: {},
    current: null,

    /* minutes -> "HH:MM" */
    fmt(min) {
      if (min == null) return '--:--';
      const m = ((Math.round(min) % 1440) + 1440) % 1440;
      return String(Math.floor(m / 60)).padStart(2, '0') + ':' + String(m % 60).padStart(2, '0');
    },
    isNight(min) { return min < 360 || min >= 1260; },
    /* "A, B, ... and Z were all in X" -> "18 students were all in X"; the names still show as chips */
    shortText(f) {
      return f.students.length > 4 ? f.text.replace(/^[^.]*? and [^.]*? were all in/, `${f.students.length} students were all in`) : f.text;
    },
    /* round avatar image (generated by pipeline/avatars.mjs); decorative, so empty alt */
    avatar: (s, px = 32) => `<img class="av" src="avatars/${App.esc(s.id)}.svg" width="${px}" height="${px}" alt="" style="border-color:${App.scoreColor(s)}">`,
    /* colour for a suspicion score; map, card lists and network all use these bands */
    scoreColor: s => (s.score >= 7 ? 'var(--alert)' : s.score >= 4 ? 'var(--warn)' : s.score > 0 ? 'var(--low)' : 'var(--clean)'),
    /* students with a score, highest first; ties by flags, then links to flagged students.
     * The mastermind is left out so the reveal stays a surprise. */
    rankSuspects() {
      if (App._ranked) return App._ranked;
      const flagged = new Set(App.data.students.filter(s => s.flagged).map(s => s.id)), links = {};
      App.data.edges.forEach(e => {
        if (flagged.has(e.b)) links[e.a] = (links[e.a] || 0) + 1;
        if (flagged.has(e.a)) links[e.b] = (links[e.b] || 0) + 1;
      });
      return (App._ranked = App.data.students.filter(s => s.score > 0 && !s.isKingpin)
        .sort((a, b) => b.score - a.score || b.flags.length - a.flags.length || (links[b.id] || 0) - (links[a.id] || 0)));
    },
    /* the case against the kingpin: time spent with students who broke a rule, and how that ranks against everyone.
     * Used by the story reveal and the case page so both quote the same numbers. */
    kingpinCase() {
      if (App._kpCase !== undefined) return App._kpCase;
      const d = App.data, kp = App.byId[d.kingpin];
      if (!kp) return (App._kpCase = null);
      const breakers = new Set(d.students.filter(s => s.flags.length).map(s => s.id));
      const mins = {}, withKp = {};
      d.edges.forEach(e => [[e.a, e.b], [e.b, e.a]].forEach(([a, b]) => {
        if (!breakers.has(b) || a === b) return;
        mins[a] = (mins[a] || 0) + (e.overlap_min || 0);
        if (a === kp.id) (withKp[b] = withKp[b] || { s: App.byId[b], min: 0, best: e }).min += e.overlap_min || 0;
        if (a === kp.id && e.overlap_min > withKp[b].best.overlap_min) withKp[b].best = e;
      }));
      const contacts = Object.values(withKp).sort((x, y) => y.min - x.min);
      const minutes = mins[kp.id] || 0;
      return (App._kpCase = { kp, contacts, minutes, breakers: breakers.size,
        rank: 1 + Object.entries(mins).filter(([id, m]) => id !== kp.id && m > minutes).length,
        students: d.students.length });
    },
    /* 898 -> "14 h 58 min" */
    dur: m => [m >= 60 && `${Math.floor(m / 60)} h`, m % 60 && `${m % 60} min`].filter(Boolean).join(' ') || '0 min',
    /* display name for a place id; claims can have no place at all */
    placeName: id => id == null ? 'No place given' : App.esc((App.placeById[id] || {}).name || id),
    /* escape data before putting it into innerHTML */
    esc: s => String(s).replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c])),
    /* flag severity -> chip class ('' = high/red); accepts med or medium */
    sev(f) { return { med: 'med', medium: 'med', low: 'low' }[String(f.severity).toLowerCase()] || ''; },

    subscribe(fn) { listeners.push(fn); },

    setState(patch) {
      const modeChanged = patch.mode && patch.mode !== state.mode;
      Object.assign(state, patch);
      if (modeChanged) App.route();
      listeners.forEach(fn => fn(state, patch));
      if (!modeChanged && App.current && App.current.update) App.current.update(state, patch);
      App.renderChrome();
    },

    selectStudent(id) {
      App.setState({ selectedStudent: id });
      if (Views.card && Views.card.open && id) Views.card.open(id);
    },

    renderChrome() {
      document.getElementById('clock-time').textContent = App.fmt(state.currentTime);
      document.getElementById('clock-icon').textContent =
        state.currentTime != null && App.isNight(state.currentTime) ? 'Night' : 'Day';
      document.querySelectorAll('.tab').forEach(t =>
        t.classList.toggle('active', t.dataset.mode === state.mode));
    },

    route() {
      const el = document.getElementById('view');
      if (App.current && App.current.unmount) App.current.unmount();
      el.innerHTML = '';
      const view = Views[state.mode];
      App.current = view || null;
      if (view) {
        view.mount(el, App.data);
        if (view.update) view.update(state, {});
      } else {
        el.innerHTML = '<div class="placeholder"><h2>' + state.mode +
          '</h2><p>This screen is built by Som. It will appear when <code>' +
          state.mode + '.js</code> registers <code>Views.' + state.mode + '</code>.</p></div>';
      }
    },

    /* The pipeline writes places in several spellings ("boyd orr building", "QMU", "the Boydy").
     * Map every one to a building id once here so all views can use placeById.
     * ponytail: belongs in build.py; delete this when the pipeline emits building ids. */
    normalise(d) {
      const key = s => String(s ?? '').toLowerCase().replace(/^the\s+/, '').replace(/[^a-z]+/g, ' ').trim();
      const ids = {};
      d.buildings.forEach(b => [b.id.replace(/_/g, ' '), b.name, b.name.replace(/\s*building$/i, '')]
        .forEach(n => (ids[key(n)] = b.id)));
      const ALIAS = {   // spoken names from testimonies -> building name
        qmu: 'queen margaret union', 'queen maragret building': 'queen margaret union',
        guu: 'glasgow university union', union: 'glasgow university union',
        hive: 'the hive', boydy: 'boyd orr building', park: 'kelvingrove park', kelvingrove: 'kelvingrove park',
        'kelvin grove': 'kelvingrove park', 'kg skate park': 'kelvingrove park', wolfson: 'wolfson medical building',
        'wolfson cafe': 'wolfson medical building', 'medicine building': 'wolfson medical building', cloisters: 'main building'
      };
      const pid = p => ids[key(ALIAS[key(p)] || p)] || p;   // unknown places ("home", "Tesco") stay as written
      // drop buildings that are only a misspelling of another one
      d.buildings = d.buildings.filter(b => !ALIAS[key(b.name)] || ids[key(ALIAS[key(b.name)])] === b.id);
      d.students.forEach(s => {
        s.stays.forEach(x => {
          x.place = pid(x.place);
          if (x.end < x.start) x.end += 1440;   // "2321-0147" crosses midnight: views expect end > start
        });
        // flags carry their time only in the text ("... 22:00–02:20 ..."); the map's live alerts need it
        s.flags.forEach(f => {
          const m = f.start == null && /(\d\d):(\d\d)\s*[–-]\s*(\d\d):(\d\d)/.exec(f.detail || '');
          if (m) { f.start = +m[1] * 60 + +m[2]; f.end = +m[3] * 60 + +m[4]; if (f.end <= f.start) f.end += 1440; }
        });
        s.claims.forEach(c => {
          c.place = pid(c.place);
          // half-open claims ("from 10 am"): assume an hour, marked so the card can say so
          if (c.start == null && c.end != null) { c.start = c.end - 60; c.approx = true; }
          if (c.end == null && c.start != null) { c.end = c.start + 60; c.approx = true; }
        });
      });
      // edges to an id missing from the student table (e.g. a mistyped ID in the logs) would crash the graph
      const known = new Set(d.students.map(s => s.id));
      const dropped = d.edges.length - (d.edges = d.edges.filter(e => known.has(e.a) && known.has(e.b))).length;
      if (dropped) console.warn(`data.json: dropped ${dropped} edges to unknown student ids`);
      d.edges.forEach(e => (e.place = pid(e.place)));
      d.findings.forEach(f => {
        // testimony findings carry their place and time only in the text: "'the park' 22:00–02:20"
        const m = f.time_start == null && /'([^']+)'\s+(\d\d):(\d\d)\s*[–-]\s*(\d\d):(\d\d)/.exec(f.text || '');
        if (m) { f.place = m[1]; f.time_start = +m[2] * 60 + +m[3]; f.time_end = +m[4] * 60 + +m[5]; }
        f.place = pid(f.place);
      });
      const maxW = Math.max(1, ...d.edges.map(e => e.weight));   // views expect weights in 0..1
      d.edges.forEach(e => (e.weight /= maxW));
    },

    // dark/light toggle; the icon shows the mode you will switch to
    initTheme() {
      const btn = document.getElementById('theme-btn'), root = document.documentElement;
      const SUN = '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round"><circle cx="12" cy="12" r="4.5"/><path d="M12 2v2M12 20v2M2 12h2M20 12h2M4.9 4.9l1.4 1.4M17.7 17.7l1.4 1.4M4.9 19.1l1.4-1.4M17.7 6.3l1.4-1.4"/></svg>';
      const MOON = '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linejoin="round"><path d="M20 14.5A8 8 0 1 1 9.5 4a6.5 6.5 0 0 0 10.5 10.5z"/></svg>';
      const paint = () => {
        const dark = root.dataset.theme !== 'light';
        btn.innerHTML = dark ? SUN : MOON;
        btn.setAttribute('aria-label', dark ? 'Switch to light mode' : 'Switch to dark mode');
      };
      btn.onclick = () => {
        root.dataset.theme = root.dataset.theme === 'light' ? 'dark' : 'light';
        try { localStorage.setItem('theme', root.dataset.theme); } catch (e) { /* private window: theme just won't persist */ }
        paint();
      };
      paint();
    },

    async boot() {
      App.initTheme();
      try {
        const res = await fetch('data.json');
        App.data = await res.json();
      } catch (e) {
        document.getElementById('view').innerHTML =
          '<div class="placeholder"><h2>Could not load data.json</h2>' +
          '<p>Open via a web server, not file://. Run <code>python -m http.server</code> in <code>web/</code>.</p></div>';
        return;
      }
      // fill fields the pipeline may leave out, so every view can rely on them
      App.data.students.forEach(s => {
        s.flags = s.flags || []; s.stays = s.stays || []; s.claims = s.claims || [];
        s.score = s.score ?? 0;
        if (/^\s*[[{]/.test(s.llm_reasoning || '')) s.llm_reasoning = null;   // pipeline sometimes writes raw JSON here
        if (s.flagged == null) s.flagged = s.flags.length > 0;
        s.isKingpin = s.id === App.data.kingpin;
        App.byId[s.id] = s;
      });
      App.normalise(App.data);
      App.data.buildings.forEach(b => (App.placeById[b.id] = b));
      document.getElementById('mock-badge').hidden = !(App.data.meta && App.data.meta.mock);
      // the only date in the data is when the pipeline generated it; the logs themselves carry times only
      const gen = App.data.meta?.generated, dEl = document.getElementById('case-date');
      if (gen && !isNaN(new Date(gen))) {
        dEl.dateTime = gen.slice(0, 10); dEl.hidden = false;
        dEl.textContent = 'Data generated ' + new Date(gen).toLocaleDateString('en-GB', { day: 'numeric', month: 'long', year: 'numeric' });
      }

      const tabs = document.getElementById('tabs');
      TABS.forEach(t => {
        const b = document.createElement('button');
        b.className = 'tab'; b.dataset.mode = t.mode; b.textContent = t.label;
        b.onclick = () => App.setState({ mode: t.mode });
        tabs.appendChild(b);
      });

      state.currentTime = 480;
      App.route();
      App.renderChrome();
    }
  };

  window.App = App;
  console.assert(App.dur(898) === '14 h 58 min' && App.dur(60) === '1 h' && App.dur(5) === '5 min', 'dur');
})();
